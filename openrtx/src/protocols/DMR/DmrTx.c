/**
 * Render the symbols of a slot into the baseband, carrying the pulse tail
 * from the previous slot.  Returns 0 when the slot has no energy.
 */
static size_t renderSlot(struct dmrTxState *state, const int8_t sym[144],
                         bool active, int16_t out[DMR_TX_SLOT_SAMPLES])
{
#ifdef DMR_TX_DEBUG_SYMS
    memcpy(dbgSyms, sym, sizeof(dbgSyms));
#endif

    if (!active) {
        /*
         * Nothing to transmit: the slot is the tail of the previous burst and
         * then silence.  Rendering 1440 samples of zeros would cost as much as
         * a real burst (measured: 176 k of 184 k instructions), and a half
         * duplex DMR slot spends half of its frames here.
         */
        const int32_t lvl = state->cfg.innerLevel;

        for (int m = 0; m < DMR_TX_CARRY_SAMPLES; m++) {
            int32_t v = (state->carry[m] * lvl) >> 14;

            if (v > 32767)
                v = 32767;
            if (v < -32768)
                v = -32768;
            out[m] = (int16_t)v;
            state->carry[m] = 0;
        }
        memset(out + DMR_TX_CARRY_SAMPLES, 0,
               (DMR_TX_SLOT_SAMPLES - DMR_TX_CARRY_SAMPLES) * sizeof(int16_t));
        return 0;
    }

    /*
     * Polyphase interpolation with the pulse tail carried from the previous
     * slot: sample m = 10 * j + p gets the contribution of every symbol s
     * whose pulse reaches it, h((j - s) + p/10).  Rendering 80 samples past
     * the slot keeps a continuous waveform (a base station never stops
     * transmitting; a handheld ramps inside the guard, which zeroes the tail).
     */
    const int32_t lvl = state->cfg.innerLevel;
    const int nrender = DMR_TX_SLOT_SAMPLES + DMR_TX_CARRY_SAMPLES;
    int32_t next[DMR_TX_CARRY_SAMPLES];
    int32_t acc;

    /*
     * Padded symbol history: four zeros on each side, so the inner loop needs
     * no bounds check.  ext[i + 4] is symbol i of the slot.
     */
    int8_t ext[DMR_TX_RRC_HALF + 144 + DMR_TX_RRC_HALF
               + DMR_TX_CARRY_SAMPLES / DMR_TX_SPS + 1];

    memset(ext, 0, sizeof(ext));
    memcpy(ext + DMR_TX_RRC_HALF, sym, 144);

    for (int m = 0; m < nrender; m++) {
        int j = m / DMR_TX_SPS;
        int p = m - j * DMR_TX_SPS;

        acc = (m < DMR_TX_CARRY_SAMPLES) ? state->carry[m] : 0;

        /* Sample m sits at t = j + p/10; symbol s contributes h(t - s). */
        const int8_t *sl = ext + j + DMR_TX_RRC_HALF;

        for (int k = -DMR_TX_RRC_HALF; k <= DMR_TX_RRC_HALF; k++)
            acc += (int32_t)dmr_tx_rrc[p][DMR_TX_RRC_HALF - k] * (int32_t)sl[k];

        if (m < DMR_TX_SLOT_SAMPLES) {
            int32_t v = (acc * lvl) >> 14;

            if (v > 32767)
                v = 32767;
            if (v < -32768)
                v = -32768;
            out[m] = (int16_t)v;
        } else {
            next[m - DMR_TX_SLOT_SAMPLES] = acc;
        }
    }

    memcpy(state->carry, next, sizeof(next));

    /*
     * PA envelope: the ramps are 1 ms raised cosines that live in the guard
     * (MS layout), so they never touch a symbol.  A base station transmits
     * continuously and does not ramp.
     */
    if ((state->cfg.layout == DMR_TX_LAYOUT_MS) && state->cfg.ramp && active) {
        const int first = MS_GUARD_SYMBOLS * DMR_TX_SPS;
        const int last = first + DMR_TX_BURST_SAMPLES; /* one past the end */

        for (int i = 0; i < RAMP_SAMPLES; i++) {
            int32_t up = dmr_tx_ramp[i];
            int32_t down = dmr_tx_ramp[RAMP_SAMPLES - 1 - i];

            out[first - RAMP_SAMPLES + i] =
                (int16_t)(((int32_t)out[first - RAMP_SAMPLES + i] * up) >> 14);
            if ((last + i) < DMR_TX_SLOT_SAMPLES)
                out[last + i] = (int16_t)(((int32_t)out[last + i] * down)
                                          >> 14);
        }

        /* Outside the ramps there is only the truncated pulse tail. */
        for (int i = 0; i < first - RAMP_SAMPLES; i++)
            out[i] = 0;
        for (int i = last + RAMP_SAMPLES; i < DMR_TX_SLOT_SAMPLES; i++)
            out[i] = 0;

        memset(state->carry, 0, sizeof(state->carry));
    }

    return active ? DMR_TX_SLOT_SAMPLES : 0;
}

size_t dmrTx_slot(struct dmrTxState *state, enum dmrTxBurst kind,
                  const uint8_t frames[DMR_FRAMES_PER_BURST][DMR_AMBE_BYTES],
                  int16_t out[DMR_TX_SLOT_SAMPLES])
{
    int8_t sym[144];
    bool active = slotSymbols(state, kind, frames, sym);

    return renderSlot(state, sym, active, out);
}
