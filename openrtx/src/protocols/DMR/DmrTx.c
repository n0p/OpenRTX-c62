/**
 * @file DmrTx.c
 * @brief DMR transmit chain, see DmrTx.h.
 *
 * Bit and symbol geometry, all from TS 102 361-1:
 *
 *   slot           144 symbols = 288 bits = 30 ms
 *   burst          132 symbols = 264 bits = 27,5 ms
 *                  98 bits payload | 10 slot type | 48 sync | 10 | 98 payload
 *   CACH           12 symbols = 24 bits = 2,5 ms (outbound only)
 *   voice payload  216 bits = three 72-bit AMBE+2 frames, contiguous from
 *                  bit 0 to 107 and bit 156 to 263 (figure 6.3: voice bursts
 *                  with a SYNC pattern have no EMB field)
 *   data payload   196 bits = BPTC(196,96) of LC(72) + RS(12,9) parity(24)
 *
 * The slot envelope is applied here and not in the chip: the FM path of the
 * BK4819 is linear in frequency but the PA still has to be keyed per slot.
 */

#include <string.h>

#include "protocols/DMR/DmrDefs.h"
#include "protocols/DMR/DmrFec.h"
#include "protocols/DMR/DmrTx.h"

/** Guard on each side of a burst, in symbols (MS layout: 1,25 ms each). */
#define MS_GUARD_SYMBOLS 6

/** Ramp length in samples: 1 ms, inside the 1,25 ms of guard. */
#define RAMP_SAMPLES 48

/** Polyphase RRC, Q14, generated by scripts/gen_dmr_tx_rrc.py. */
extern const int16_t dmr_tx_rrc[DMR_TX_RRC_PHASES][DMR_TX_RRC_SPAN];

/** PA ramp, Q14 raised cosine 0 -> 1, same generator. */
extern const int16_t dmr_tx_ramp[RAMP_SAMPLES];

/** Dibit to symbol level: 0,1 are the negative half, 2,3 the positive one. */
static const int8_t dibitLevel[4] = { -1, -3, 1, 3 };

/**
 * Write one symbol of a burst as its two bits.  The mapping is the inverse of
 * dibitLevel(): -3 is dibit 1 (bits 0,1), not 0.  A sync symbol written as
 * bits 0,0 lands on -1 instead of -3: the receiver still matches the sync by
 * sign, so the mistake hides -- and then the sync field, which is the level
 * and timing reference of the whole burst, is 2 levels off.
 */
static void putSymbol(uint8_t *bits, int symbol, int level)
{
    int dibit = (level == -3) ? 1 : (level == -1) ? 0 : (level == 1) ? 2 : 3;

    bits[2 * symbol] = (uint8_t)((dibit >> 1) & 1u);
    bits[2 * symbol + 1] = (uint8_t)(dibit & 1u);
}

/**
 * A burst being built: 264 bits, in the on-air order the receiver reads.
 */
struct burstBits {
    uint8_t b[DMR_BURST_BITS];
};

static void putBits(uint8_t *dst, int nbits, uint32_t value)
{
    for (int i = 0; i < nbits; i++)
        dst[i] = (uint8_t)((value >> (nbits - 1 - i)) & 1u);
}

void dmrTx_linkControl(uint8_t lc[12], uint32_t srcId, uint32_t dstId,
                       bool group, uint8_t dataType)
{
    uint8_t bits[72];

    /*
     * Full LC PDU (TS 102 361-1 table 9.10): PF(1) reserved(1) FLCO(6) FID(8)
     * SO(8) DST(24) SRC(24).  FLCO 0x00 is a group voice channel user, 0x03 a
     * unit-to-unit voice call; FID 0x00 is the standard feature set.
     */
    const uint8_t flco = group ? 0x00 : 0x03;

    putBits(bits, 1, 0);         /* PF: not a protected LC */
    putBits(bits + 1, 1, 0);     /* reserved */
    putBits(bits + 2, 6, flco);
    putBits(bits + 8, 8, 0x00);  /* FID */
    putBits(bits + 16, 8, 0x00); /* service options */
    putBits(bits + 24, 24, dstId);
    putBits(bits + 48, 24, srcId);

    memset(lc, 0, 12);
    for (int i = 0; i < 72; i++)
        lc[i >> 3] |= (uint8_t)(bits[i] << (7 - (i & 7)));

    dmr_fec_rs129_encode(lc, dataType);
}

/** Pack 20 bits of a Golay(20,8) slot type field around the sync. */
static void putSlotType(struct burstBits *burst, uint8_t info)
{
    uint32_t cw = dmr_fec_golay_encode(info);

    for (int i = 0; i < 10; i++) {
        burst->b[98 + i] = (uint8_t)((cw >> (19 - i)) & 1u);
        burst->b[156 + i] = (uint8_t)((cw >> (9 - i)) & 1u);
    }
}

/** 24-bit CACH: AT, TC, LS1, LS0 + 17 payload bits + three parity bits. */
static void buildCach(uint8_t cach[24], const struct dmrTxConfig *cfg,
                      bool audio)
{
    memset(cach, 0, 24);

    cach[dmr_cach_tact_pos[0]] = audio ? 1 : 0;          /* AT */
    cach[dmr_cach_tact_pos[1]] = cfg->timeslot ? 1 : 0;  /* TC */
    cach[dmr_cach_tact_pos[2]] = cfg->lateEntry ? 1 : 0; /* LS1 */
    cach[dmr_cach_tact_pos[3]] = 0;                      /* LS0 */

    /* Short LC: the empty one, all zero payload (as a repeater idles) */
    for (int i = 0; i < 17; i++)
        cach[dmr_cach_payload_pos[i]] = 0;

    dmr_fec_cach_encode(cach);
}

/** Turn 24 bits of CACH into 12 symbols. */
static void cachSymbols(const uint8_t cach[24], int8_t sym[12])
{
    for (int i = 0; i < 12; i++) {
        int dibit = ((cach[2 * i] & 1u) << 1) | (cach[2 * i + 1] & 1u);

        sym[i] = dibitLevel[dibit];
    }
}

void dmrTx_init(struct dmrTxState *state, const struct dmrTxConfig *cfg)
{
    memset(state, 0, sizeof(*state));
    state->cfg = *cfg;
    if (state->cfg.innerLevel == 0)
        state->cfg.innerLevel = 2731; /* 1944 Hz outer, 0,25 FS */
}

void dmrTx_setCall(struct dmrTxState *state, uint8_t colourCode,
                   uint32_t sourceId, uint32_t destId, bool group)
{
    state->cfg.colourCode = colourCode;
    state->cfg.sourceId = sourceId;
    state->cfg.destId = destId;
    state->cfg.group = group;
}

/**
 * Sync word of a burst: the mobile station's in the handheld layout (the
 * inbound channel carries what a portable sends) and the base station's in the
 * repeater layout.  Both are in the receiver's search set, so the loopback
 * decodes either; a real repeater only answers the MS word and only ever sends
 * the BS one.
 */
static enum dmrSync syncWord(const struct dmrTxConfig *cfg, bool voice)
{
    if (cfg->layout == DMR_TX_LAYOUT_BS)
        return voice ? DMR_SYNC_BS_VOICE : DMR_SYNC_BS_DATA;

    return voice ? DMR_SYNC_MS_VOICE : DMR_SYNC_MS_DATA;
}

/** Render a slot worth of symbols, defined after dmrTx_dataSlot(). */
static size_t renderSlot(struct dmrTxState *state, const int8_t sym[144],
                         bool active, int16_t out[DMR_TX_SLOT_SAMPLES]);

void dmrTx_dataTerminator(uint8_t lc[12], uint32_t srcId, uint32_t dstId,
                          bool group)
{
    uint8_t bits[72];

    /*
     * Terminator Data Link Control (TS 102 361-3 table 7.1): PF, reserved,
     * FLCO 110000, FID 0, destination, source, then G/I, A, FMF, reserved,
     * S and N(S) 0.  It is what closes a data call, so the receivers in the
     * talkgroup stop waiting for more blocks.
     */
    putBits(bits, 1, 0);         /* PF */
    putBits(bits + 1, 1, 0);     /* reserved */
    putBits(bits + 2, 6, 0x30);  /* FLCO: terminator with LC */
    putBits(bits + 8, 8, 0x00);  /* FID */
    putBits(bits + 16, 24, dstId);
    putBits(bits + 40, 24, srcId);
    putBits(bits + 64, 1, group ? 1 : 0); /* G/I */
    putBits(bits + 65, 1, 0);            /* A: no response requested */
    putBits(bits + 66, 1, 1);            /* FMF: last (and only) fragment */
    putBits(bits + 67, 1, 0);            /* reserved */
    putBits(bits + 68, 1, 0);            /* S: no resynchronisation */
    putBits(bits + 69, 3, 0);            /* N(S) */

    memset(lc, 0, 12);
    for (int i = 0; i < 72; i++)
        lc[i >> 3] |= (uint8_t)(bits[i] << (7 - (i & 7)));

    dmr_fec_rs129_encode(lc, (uint8_t)DMR_DT_TERMINATOR_LC);
}

/**
 * Fill the 264 bits of a data burst: the slot type and sync around the
 * BPTC(196,96) codeword of 96 information bits.
 *
 * @param burst: destination, already zeroed.
 * @param cfg: colour code, layout and call of the transmission.
 * @param dataType: burst data type, TS 102 361-1 table 6.6.
 * @param data: 96 information bits, one per element.
 */
static void dataBurstBits(struct burstBits *burst, const struct dmrTxConfig *cfg,
                          uint8_t dataType, const uint8_t data[96])
{
    uint8_t enc[DMR_INFO_BITS];
    int8_t s[DMR_SYNC_SYMBOLS];

    dmr_fec_bptc_encode(data, enc);
    for (int i = 0; i < 98; i++)
        burst->b[i] = enc[i];
    for (int i = 0; i < 98; i++)
        burst->b[166 + i] = enc[98 + i];

    putSlotType(burst, (uint8_t)((cfg->colourCode << 4) | (dataType & 0x0F)));

    dmr_sync_symbols(syncWord(cfg, false), s);
    for (int i = 0; i < DMR_SYNC_SYMBOLS; i++)
        putSymbol(burst->b, 54 + i, s[i]);
}

/**
 * The 264 bits of a burst to the 144 symbols of the slot: CACH then burst in
 * the base station layout, guard then burst in the handheld one.
 */
static void layoutSymbols(const struct dmrTxConfig *cfg,
                          const struct burstBits *burst, bool audio,
                          int8_t sym[144])
{
    int8_t bs[DMR_BURST_SYMBOLS];

    for (int i = 0; i < DMR_BURST_SYMBOLS; i++) {
        int dibit = ((burst->b[2 * i] & 1u) << 1) | (burst->b[2 * i + 1] & 1u);

        bs[i] = dibitLevel[dibit];
    }

    if (cfg->layout == DMR_TX_LAYOUT_BS) {
        uint8_t cach[24];

        buildCach(cach, cfg, audio);
        cachSymbols(cach, sym);
        memcpy(sym + DMR_CACH_SYMBOLS, bs, DMR_BURST_SYMBOLS);
    } else {
        memcpy(sym + MS_GUARD_SYMBOLS, bs, DMR_BURST_SYMBOLS);
    }
}

/**
 * Fill sym[144] with the symbols of the slot, and return true if the slot
 * carries energy.
 */
static bool
slotSymbols(struct dmrTxState *state, enum dmrTxBurst kind,
            const uint8_t frames[DMR_FRAMES_PER_BURST][DMR_AMBE_BYTES],
            int8_t sym[144])
{
    const struct dmrTxConfig *cfg = &state->cfg;
    struct burstBits burst;
    bool audio = false;

    memset(sym, 0, 144);
    memset(&burst, 0, sizeof(burst));

    switch (kind) {
        case DMR_TXB_EMPTY:
            return false;

        case DMR_TXB_VOICE: {
            audio = true;

            /*
             * 216 payload bits: three frames, interleaved.  Figure 6.3 puts
             * them contiguously around the SYNC pattern: 108 bits, then the
             * 48-bit sync, then 108 bits.
             */
            uint8_t payload[DMR_PAYLOAD_BITS];

            for (int f = 0; f < DMR_FRAMES_PER_BURST; f++)
                dmr_fec_voice_interleave(frames[f],
                                         payload + f * DMR_AMBE_BITS);

            for (int i = 0; i < DMR_HALF_BITS; i++)
                burst.b[i] = payload[i];
            for (int i = 0; i < DMR_HALF_BITS; i++)
                burst.b[156 + i] = payload[DMR_HALF_BITS + i];

            int8_t s[DMR_SYNC_SYMBOLS];

            dmr_sync_symbols(syncWord(cfg, true), s);
            for (int i = 0; i < DMR_SYNC_SYMBOLS; i++)
                putSymbol(burst.b, 54 + i, s[i]);

            state->voiceBurst = (uint8_t)((state->voiceBurst + 1) % 6);
            break;
        }

        case DMR_TXB_VOICE_LC:
        case DMR_TXB_TERMINATOR:
        case DMR_TXB_IDLE: {
            uint8_t lc[12];
            uint8_t data[96];

            if (kind == DMR_TXB_IDLE) {
                memset(data, 0, sizeof(data));
                dataBurstBits(&burst, cfg, (uint8_t)DMR_DT_IDLE, data);
            } else {
                uint8_t dt = (uint8_t)(kind == DMR_TXB_VOICE_LC
                                           ? DMR_DT_VOICE_LC_HEADER
                                           : DMR_DT_TERMINATOR_LC);

                dmrTx_linkControl(lc, cfg->sourceId, cfg->destId, cfg->group,
                                  dt);
                for (int i = 0; i < 96; i++)
                    data[i] = (uint8_t)((lc[i >> 3] >> (7 - (i & 7))) & 1u);
                dataBurstBits(&burst, cfg, dt, data);
            }
            break;
        }

        case DMR_TXB_DATA:
            /* only reachable through dmrTx_dataSlot() */
            return false;
    }

    layoutSymbols(cfg, &burst, audio, sym);
    return true;
}

size_t dmrTx_dataSlot(struct dmrTxState *state, uint8_t dataType,
                      const uint8_t info[96], int16_t out[DMR_TX_SLOT_SAMPLES])
{
    struct burstBits burst;
    int8_t sym[144];

    memset(&burst, 0, sizeof(burst));
    memset(sym, 0, sizeof(sym));

    dataBurstBits(&burst, &state->cfg, dataType, info);
    layoutSymbols(&state->cfg, &burst, false, sym);
    return renderSlot(state, sym, true, out);
}

