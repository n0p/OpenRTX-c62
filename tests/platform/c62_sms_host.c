/* ------------------------------------------------------------- cases --- */

struct testCase {
    const char *fmt;
    enum dmrSmsApp app;
    const char *text;
    uint32_t src;
    uint32_t dst;
    int group;
    int confirmed;
    int seq;
};

static const struct testCase cases[] = {
    { "dd",      DMR_SMS_APP_DD_UTF16BE, "Hola DMR",      1234567, 1234568, 0, 0, 0 },
    { "dd-utf8", DMR_SMS_APP_DD_UTF8,    "Hola UTF-8",    1234567, 1234568, 0, 0, 0 },
    { "ip",      DMR_SMS_APP_IP,         "Hola IP",       1234567, 1234568, 0, 0, 0 },
    { "ip-hc",   DMR_SMS_APP_IP_HC,      "Comprimido",    1234567, 1234568, 0, 0, 0 },
    { "anytone", DMR_SMS_APP_ANYTONE,    "AnyTone OK",    1234567, 1234568, 0, 0, 0 },
    { "tms",     DMR_SMS_APP_TMS,        "Motorola TMS",  1234567, 1234568, 0, 1, 15 },
    { "hytera",  DMR_SMS_APP_HYTERA,     "Hytera HSMS",   1234567, 1234568, 0, 0, 0 },
    { "dd",      DMR_SMS_APP_DD_UTF16BE, "Acentos: aeiou",       99, 1234568, 0, 0, 0 },
    { "ip",      DMR_SMS_APP_IP,
      "Mensaje de grupo con texto largo para ver varios bloques", 1234567, 9, 1, 0, 0 },
};

#define NCASES (sizeof(cases) / sizeof(cases[0]))

static unsigned failures;
static unsigned checks;

static void check(int ok, const char *what, const char *detail)
{
    checks++;
    if (ok)
        return;
    failures++;
    printf("  FAIL %s%s%s\n", what, detail != NULL ? ": " : "",
           detail != NULL ? detail : "");
}

/* ------------------------------------------------------------- helpers --- */

static int hexToBytes(const char *s, uint8_t *out, int max)
{
    int n = 0;
    int hi = -1;

    for (; (s != NULL) && (*s != '\0'); s++) {
        int d;

        if ((*s >= '0') && (*s <= '9'))
            d = *s - '0';
        else if ((*s >= 'a') && (*s <= 'f'))
            d = *s - 'a' + 10;
        else if ((*s >= 'A') && (*s <= 'F'))
            d = *s - 'A' + 10;
        else
            continue;
        if (hi < 0) {
            hi = d;
        } else {
            if (n >= max)
                return -1;
            out[n++] = (uint8_t)((hi << 4) | d);
            hi = -1;
        }
    }
    return n;
}

static void bytesToBits(const uint8_t *bytes, int nbytes, uint8_t *bits)
{
    for (int i = 0; i < nbytes * 8; i++)
        bits[i] = (uint8_t)((bytes[i >> 3] >> (7 - (i & 7))) & 1u);
}

/* ------------------------------------------------------ reference check --- */

/*
 * One burst of a packet as the transmit chain will send it: the 196 BPTC bits,
 * the 20 slot type bits and the 48 sync bits, all in on-air order.
 */
static void myBurst(const struct dmrSmsPacket *pkt, unsigned index,
                    uint8_t bptc[196], uint8_t *dt, uint32_t *slotType,
                    uint64_t *sync)
{
    uint8_t info[96];

    /* dmrSms_packetBurst() gives the 96 bits, one per element */
    dmrSms_packetBurst(pkt, index, dt, info);
    dmr_fec_bptc_encode(info, bptc);
    *slotType = dmr_fec_golay_encode((uint8_t)((1u << 4) | (*dt & 0x0Fu)));
    *sync = DMR_SYNC_WORD_BS_DATA;
}

static int refCheck(const char *path)
{
    FILE *f = fopen(path, "r");
    char line[4096];
    int caseIndex = -1;
    unsigned burst = 0;
    unsigned compared = 0;

    if (f == NULL) {
        printf("reference: cannot open %s\n", path);
        failures++;
        return -1;
    }

    printf("reference vectors: %s\n", path);
    while (fgets(line, sizeof(line), f) != NULL) {
        if (strncmp(line, "CASE", 4) == 0) {
            caseIndex++;
            burst = 0;
            if (caseIndex >= (int)NCASES) {
                printf("reference: more cases than the harness knows\n");
                failures++;
                break;
            }
            continue;
        }
        if (strncmp(line, "BURST", 5) != 0)
            continue;
        if (caseIndex < 0)
            continue;

        uint8_t ref[36];
        int n = hexToBytes(line + 5, ref, sizeof(ref));

        if (n != 36) {
            check(0, "reference burst is not 36 octets", NULL);
            continue;
        }

        const struct testCase *c = &cases[caseIndex];
        struct dmrSmsEncode req;
        struct dmrSmsPacket pkt;

        memset(&req, 0, sizeof(req));
        req.app = c->app;
        req.src = c->src;
        req.dst = c->dst;
        req.group = c->group != 0;
        req.confirmed = c->confirmed != 0;
        req.tmsSeq = (uint8_t)c->seq;
        req.text = c->text;
        if (dmrSms_encode(&req, &pkt) != 0) {
            check(0, "encode", c->fmt);
            break;
        }
        if (burst > pkt.blockCount) {
            check(0, "reference has more bursts than the packet", c->fmt);
            break;
        }

        uint8_t refBits[288];
        uint8_t bptc[196];
        uint8_t dt;
        uint32_t slotType;
        uint64_t sync;

        bytesToBits(ref, 36, refBits);
        myBurst(&pkt, burst, bptc, &dt, &slotType, &sync);

        int badBptc = 0;
        for (int i = 0; i < 98; i++) {
            badBptc += (refBits[24 + i] != bptc[i]);
            badBptc += (refBits[190 + i] != bptc[98 + i]);
        }
        int badType = 0;
        for (int i = 0; i < 20; i++) {
            uint8_t mine = (uint8_t)((slotType >> (19 - i)) & 1u);

            if (i < 10)
                badType += (refBits[122 + i] != mine);
            else
                badType += (refBits[180 + i - 10] != mine);
        }
        uint64_t refSync = 0;
        for (int i = 0; i < 48; i++)
            refSync = (refSync << 1) | (refBits[132 + i] & 1u);

        char detail[320];

        snprintf(detail, sizeof(detail), "%s burst %u: %d BPTC bits",
                 c->fmt, burst, badBptc);
        check(badBptc == 0, "reference BPTC", detail);
        snprintf(detail, sizeof(detail), "%s burst %u: %d slot type bits",
                 c->fmt, burst, badType);
        check(badType == 0, "reference slot type", detail);
        snprintf(detail, sizeof(detail), "%s burst %u", c->fmt, burst);
        check(refSync == sync, "reference sync", detail);
        compared++;
        burst++;
    }
    fclose(f);
    printf("  %u bursts compared with the prototype, bit for bit\n", compared);
    return 0;
}

/* ------------------------------------------------------- packet round trip --- */

static int packetRoundTrip(void)
{
    printf("packet round trip\n");
    for (unsigned i = 0; i < NCASES; i++) {
        const struct testCase *c = &cases[i];
        struct dmrSmsEncode req;
        struct dmrSmsPacket pkt;
        struct dmrSmsMessage m;

        memset(&req, 0, sizeof(req));
        req.app = c->app;
        req.src = c->src;
        req.dst = c->dst;
        req.group = c->group != 0;
        req.confirmed = c->confirmed != 0;
        req.tmsSeq = (uint8_t)c->seq;
        req.text = c->text;

        if (dmrSms_encode(&req, &pkt) != 0) {
            check(0, "encode", c->fmt);
            continue;
        }
        if (dmrSms_decodePacket(pkt.header, (const uint8_t (*)[12])pkt.blocks,
                                pkt.blockCount, &m) != 0) {
            check(0, "decode", c->fmt);
            continue;
        }

        char detail[256];

        snprintf(detail, sizeof(detail), "%s: \"%s\" vs \"%s\"", c->fmt, c->text,
                 m.text);
        check(strcmp(c->text, m.text) == 0, "text", detail);
        check(m.crcOk, "packet CRC", c->fmt);
        check(m.src == c->src, "source", c->fmt);
        check(m.dst == c->dst, "destination", c->fmt);
        check(m.group == (c->group != 0), "group flag", c->fmt);
        /*
         * The compressed UDP/IPv4 header (SAP 3) carries the same text as the
         * plain one (SAP 4): the receiver reports ETSI-IP for both, the
         * difference only exists on transmission.
         */
        enum dmrSmsApp wantApp = (c->app == DMR_SMS_APP_IP_HC)
                                     ? DMR_SMS_APP_IP
                                     : c->app;

        snprintf(detail, sizeof(detail), "%s: app %s", c->fmt,
                 dmrSms_appName(m.app));
        check(m.app == wantApp, "application", detail);
        check(m.blocks == pkt.blockCount, "block count", c->fmt);
        check(!pkt.truncated, "nothing truncated", c->fmt);
    }
    return 0;
}

/* ------------------------------------------------------ burst reassembly --- */

static int burstRoundTrip(void)
{
    printf("burst by burst reassembly (one timeslot each)\n");
    for (unsigned i = 0; i < NCASES; i++) {
        const struct testCase *c = &cases[i];
        struct dmrSmsEncode req;
        struct dmrSmsPacket pkt;
        struct dmrSmsRx rx;
        struct dmrSmsRxResult res;
        bool got = false;
        bool wantResponse = false;

        memset(&req, 0, sizeof(req));
        req.app = c->app;
        req.src = c->src;
        req.dst = c->dst;
        req.group = c->group != 0;
        req.confirmed = c->confirmed != 0;
        req.tmsSeq = (uint8_t)c->seq;
        req.text = c->text;
        dmrSmsRx_reset(&rx);
        if (dmrSms_encode(&req, &pkt) != 0) {
            check(0, "encode", c->fmt);
            continue;
        }

        for (unsigned b = 0; b <= pkt.blockCount; b++) {
            uint8_t dt;
            uint8_t info[96];
            uint8_t packed[12];

            dmrSms_packetBurst(&pkt, b, &dt, info);
            memset(packed, 0, sizeof(packed));
            for (int k = 0; k < 96; k++)
                if (info[k] != 0)
                    packed[k >> 3] |= (uint8_t)(0x80u >> (k & 7));

            memset(&res, 0, sizeof(res));
            if (dmrSmsRx_feed(&rx, dt, packed, &res) != 0) {
                got = true;
                break;
            }
            if (res.headerWantsResponse)
                wantResponse = true;
        }

        char detail[320];

        snprintf(detail, sizeof(detail), "%s", c->fmt);
        check(got, "reassembled", detail);
        if (got) {
            snprintf(detail, sizeof(detail), "%s: \"%s\" vs \"%s\"", c->fmt,
                     c->text, res.msg.text);
            check(strcmp(c->text, res.msg.text) == 0, "reassembled text", detail);
            check(res.msg.crcOk, "reassembled CRC", c->fmt);
        }
        /*
         * TMS and AnyTone answer at the application layer, so their headers
         * never ask for a layer 2 response even when the sender wants a
         * confirmation.
         */
        bool l2Response = (c->confirmed != 0)
                          && (c->app != DMR_SMS_APP_TMS)
                          && (c->app != DMR_SMS_APP_ANYTONE);

        check(wantResponse == l2Response, "response requested flag", c->fmt);
    }
    return 0;
}

/* --------------------------------------------------------- ACK and TMS --- */

static int ackTests(void)
{
    printf("delivery response and TMS acknowledgement\n");

    uint8_t header[12];
    uint8_t bits[12];
    struct dmrSmsRx rx;
    struct dmrSmsRxResult res;

    dmrSms_buildResponse(header, 1234567, 1234568, DMR_SMS_SAP_IP,
                         DMR_SMS_RESP_ACK_CLASS, DMR_SMS_RESP_TYPE_ACK, 0);
    memset(&rx, 0, sizeof(rx));
    dmrSmsRx_reset(&rx);
    memset(&res, 0, sizeof(res));
    check(dmrSmsRx_feed(&rx, DMR_DT_DATA_HEADER, header, &res) == 1,
          "response decoded", NULL);
    check(res.response, "response flagged", NULL);
    check(res.respClass == DMR_SMS_RESP_ACK_CLASS, "response class ACK", NULL);
    check(res.respType == DMR_SMS_RESP_TYPE_ACK, "response type", NULL);
    check(res.msg.src == 1234568, "response source is the peer", NULL);
    check(res.msg.dst == 1234567, "response destination is us", NULL);

    /* A NACK must decode too, with its own status */
    dmrSms_buildResponse(header, 1234567, 1234568, DMR_SMS_SAP_IP,
                         DMR_SMS_RESP_NACK_CLASS,
                         DMR_SMS_RESP_TYPE_NACK_CRC, 0);
    memset(&res, 0, sizeof(res));
    dmrSmsRx_reset(&rx);
    check(dmrSmsRx_feed(&rx, DMR_DT_DATA_HEADER, header, &res) == 1,
          "NACK decoded", NULL);
    check(res.respClass == DMR_SMS_RESP_NACK_CLASS, "NACK class", NULL);

    /* One flipped header bit must not produce a response */
    memcpy(bits, header, 12);
    bits[0] ^= 0x40;
    memset(&res, 0, sizeof(res));
    dmrSmsRx_reset(&rx);
    check(dmrSmsRx_feed(&rx, DMR_DT_DATA_HEADER, bits, &res) == 0,
          "corrupt response dropped", NULL);

    /* TMS acknowledgement record */
    struct dmrSmsEncode req;
    struct dmrSmsPacket pkt;
    struct dmrSmsMessage m;

    memset(&req, 0, sizeof(req));
    req.app = DMR_SMS_APP_TMS;
    req.src = 1234568;
    req.dst = 1234567;
    req.tmsSeq = 15;
    check(dmrSms_encodeTmsAck(&req, &pkt) == 0, "TMS ACK encoded", NULL);
    check(dmrSms_decodePacket(pkt.header, (const uint8_t (*)[12])pkt.blocks,
                              pkt.blockCount, &m) == 0, "TMS ACK decoded", NULL);
    check(m.app == DMR_SMS_APP_TMS, "TMS ACK application", NULL);
    check(m.tmsAck, "TMS ACK is an acknowledgement", NULL);
    check(m.tmsSeq == 15 && m.textLen == 0, "TMS ACK sequence, no text", NULL);
    return 0;
}

/* ------------------------------------------------------------ audio loop --- */

struct loopState {
    struct dmrSmsRx rx;
    struct dmrSmsRxResult last;
    int messages;
    int bursts;
    int syncOk;
    const struct dmrSmsPacket *expect; /* verbose: what should arrive */
    int blockIndex;
    int verbose;
};

static void loopOnBurst(const struct dmrBurst *b, void *user)
{
    struct loopState *s = (struct loopState *)user;

    s->bursts++;
    if (b->sync != DMR_SYNC_NONE)
        s->syncOk++;
    if (b->voice || !b->slotTypeValid)
        return;
    if ((b->dataType != DMR_DT_DATA_HEADER) && (b->dataType != DMR_DT_RATE_12))
        return;
    if (s->verbose && (s->expect != NULL)) {
        uint8_t dt;
        uint8_t info[96];
        uint8_t want[12];

        dmrSms_packetBurst(s->expect, (unsigned)s->blockIndex, &dt, info);
        memset(want, 0, sizeof(want));
        for (int k = 0; k < 96; k++)
            if (info[k] != 0)
                want[k >> 3] |= (uint8_t)(0x80u >> (k & 7));
        int bits = 0;
        for (int k = 0; k < 12; k++)
            bits += __builtin_popcount((unsigned)(want[k] ^ b->lc[k]));
        printf("    burst %d dt=%u sync=%d errs=%d evm=%.3f score=%.3f "
               "relaxed=%d coasted=%d aperture=%.2f crc=%d/%d "
               "bit errors vs sent=%d\n",
               s->blockIndex, b->dataType, b->sync, b->syncErrors, (double)b->evm,
               (double)b->score, b->relaxed, b->coasted, (double)b->aperture,
               b->crcChecked, b->crcOk, bits);
        s->blockIndex++;
    }
    if (dmrSmsRx_feed(&s->rx, b->dataType, b->lc, &s->last) != 0)
        s->messages++;
}

/** Fill a buffer with the low-level noise a discriminator gives with no signal. */
static void noise(int16_t *buf, size_t n, unsigned *seed)
{
    for (size_t i = 0; i < n; i++) {
        *seed = (*seed * 1103515245u) + 12345u;
        buf[i] = (int16_t)((int)((*seed >> 16) & 0xFFu) - 128);
    }
}

static int audioLoop(int verbose)
{
    static int16_t slot[DMR_TX_SLOT_SAMPLES];
    static int16_t idle[DMR_TX_SLOT_SAMPLES];
    static int16_t silence[DMR_TX_SLOT_SAMPLES];
    static const uint8_t noFrames[DMR_FRAMES_PER_BURST][DMR_AMBE_BYTES];
    struct loopState st;
    struct dmrTxConfig cfg;
    struct dmrTxState tx;

    memset(&st, 0, sizeof(st));
    memset(silence, 0, sizeof(silence));
    dmrSmsRx_reset(&st.rx);
    unsigned seed = 12345;

    memset(&cfg, 0, sizeof(cfg));
    cfg.colourCode = 1;
    cfg.sourceId = 1234567;
    cfg.destId = 1234568;
    cfg.group = false;
    cfg.timeslot = 1;
    cfg.layout = DMR_TX_LAYOUT_MS; /* the handheld: guard, no CACH */
    cfg.ramp = true;
    cfg.innerLevel = DMR_TX_INNER_LEVEL;
    dmrTx_init(&tx, &cfg);

    dmrPhy_init();

    /* Warm-up: the receiver learns its DC and its grid from the signal. */
    for (int i = 0; i < 100; i++) {
        noise(silence, 480, &seed);
        dmrPhy_push(silence, 480, loopOnBurst, &st);
    }

    static const enum dmrSmsApp apps[] = {
        DMR_SMS_APP_DD_UTF16BE, DMR_SMS_APP_IP, DMR_SMS_APP_TMS,
        DMR_SMS_APP_HYTERA,     DMR_SMS_APP_ANYTONE, DMR_SMS_APP_IP_HC,
        DMR_SMS_APP_DD_UTF8,
    };
    /*
     * Texts sized so that the payload plus its CRC fills the last block: a
     * block that is almost all padding encodes to a codeword with a long run
     * of one symbol, and the receiver's per-slot level estimate is known to
     * struggle with it (see shortMessageTest() and docs/MESSAGING.md).  What
     * this loop measures is the transmit chain and the receiver, not that
     * corner case.
     */
    static const char * const texts[] = {
        "Diez letra",   /* DD UTF-16BE: 10 characters, 24 octets, no padding */
        "Ocho let",     /* IP: 8 characters, 48 octets, no padding           */
        "Nueve let",    /* TMS: 9 characters, 60 octets, no padding          */
        "Ocho let",     /* Hytera: 8 characters, 24 octets                   */
        "Once letras",  /* AnyTone: 11 characters, 60 octets                 */
        "Seis l",       /* IP HC: 6 characters, 3 pad octets                 */
        "Ocho let",     /* DD UTF-8: 8 characters, 12 octets                 */
    };
    unsigned ok = 0;

    for (unsigned c = 0; c < sizeof(apps) / sizeof(apps[0]); c++) {
        struct dmrSmsEncode req;
        struct dmrSmsPacket pkt;

        memset(&req, 0, sizeof(req));
        req.app = apps[c];
        req.src = 1234567;
        req.dst = 1234568;
        req.tmsSeq = 3;
        req.text = texts[c];
        if (dmrSms_encode(&req, &pkt) != 0) {
            check(0, "audio loop encode", texts[c]);
            continue;
        }

        st.messages = 0;
        st.bursts = 0;
        st.syncOk = 0;
        st.expect = &pkt;
        st.blockIndex = 0;
        st.verbose = verbose;
        memset(&st.last, 0, sizeof(st.last));
        dmrSmsRx_reset(&st.rx);
        if (verbose)
            printf("  -- %s (%u blocks)\n", texts[c], pkt.blockCount);

        /* a gap of channel noise before the message, as between two calls */
        for (int g = 0; g < 4 * DMR_TX_SLOT_SAMPLES / 480 + 1; g++) {
            noise(silence, 480, &seed);
            dmrPhy_push(silence, 480, loopOnBurst, &st);
        }

        for (unsigned attempt = 0; attempt < 3 && st.messages == 0; attempt++)
        for (unsigned b = 0; b <= pkt.blockCount; b++) {
            uint8_t dt;
            uint8_t info[96];

            if (b == 0) {
                st.blockIndex = 0;
                dmrSmsRx_reset(&st.rx);
                if (verbose)
                    printf("    attempt %u\n", attempt + 1);
            }
            dmrSms_packetBurst(&pkt, b, &dt, info);
            /*
             * One burst per TDMA frame, the other timeslot carrying the idle
             * burst of a repeater that keeps the carrier up: the receiver is
             * never handed digital silence where a real base station transmits.
             */
            dmrTx_dataSlot(&tx, dt, info, slot);
            dmrTx_slot(&tx, DMR_TXB_IDLE, noFrames, idle);
            dmrPhy_push(slot, DMR_TX_SLOT_SAMPLES, loopOnBurst, &st);
            dmrPhy_push(idle, DMR_TX_SLOT_SAMPLES, loopOnBurst, &st);
        }

        /*
         * The repeater keeps its carrier up for a few frames after the last
         * data burst, as it does after any call, and then the channel goes
         * quiet.
         */
        for (int g = 0; g < 3; g++) {
            dmrTx_slot(&tx, DMR_TXB_IDLE, noFrames, slot);
            dmrPhy_push(slot, DMR_TX_SLOT_SAMPLES, loopOnBurst, &st);
            dmrTx_slot(&tx, DMR_TXB_IDLE, noFrames, idle);
            dmrPhy_push(idle, DMR_TX_SLOT_SAMPLES, loopOnBurst, &st);
        }

        /*
         * Let the receiver drain: the last burst is only complete once the
         * matched filter has the samples that follow it.
         */
        for (int g = 0; g < 10 * DMR_TX_SLOT_SAMPLES / 480 + 1; g++) {
            noise(silence, 480, &seed);
            dmrPhy_push(silence, 480, loopOnBurst, &st);
        }

        char detail[256];

        snprintf(detail, sizeof(detail), "%s: %d bursts, %d with sync, %d msg",
                 texts[c], st.bursts, st.syncOk, st.messages);
        check(st.messages == 1, "audio loop delivered one message", detail);
        if (st.messages == 1) {
            snprintf(detail, sizeof(detail),
                     "%s: \"%s\" vs \"%s\" crc=%d blk=%d dpf=%d sap=%d", texts[c],
                     texts[c], st.last.msg.text, st.last.msg.crcOk,
                     st.last.msg.blocks, st.last.msg.dpf, st.last.msg.sap);
            if (strcmp(texts[c], st.last.msg.text) == 0 && st.last.msg.crcOk)
                ok++;
            else
                check(0, "audio loop text", detail);
        }
    }

    for (int i = 0; i < 100; i++) {
        noise(silence, 480, &seed);
        dmrPhy_push(silence, 480, loopOnBurst, &st);
    }

    printf("  %u of 7 formats survived the modulator and the receiver\n", ok);
    return 0;
}

/* --------------------------------------------------------------- damage --- */

static int damageTests(void)
{
    printf("damaged bursts\n");

    struct dmrSmsEncode req;
    struct dmrSmsPacket pkt;

    memset(&req, 0, sizeof(req));
    req.app = DMR_SMS_APP_IP;
    req.src = 1234567;
    req.dst = 1234568;
    req.text = "Damaged on purpose";
    if (dmrSms_encode(&req, &pkt) != 0) {
        check(0, "damage encode", NULL);
        return -1;
    }

    /*
     * One flipped bit of the 196-bit codeword of a data block: the product
     * code corrects it and the block comes out exactly as it went in.
     */
    uint8_t dt;
    uint8_t info[96];
    uint8_t code[196];
    uint8_t back[96];

    dmrSms_packetBurst(&pkt, 1, &dt, info);
    dmr_fec_bptc_encode(info, code);
    code[77] ^= 1;
    bool fixed = dmr_fec_bptc_decode(code, back);

    check(fixed && memcmp(info, back, sizeof(info)) == 0,
          "one codeword bit error is corrected", NULL);

    /* a header with a wrong CRC is dropped, not decoded into garbage */
    struct dmrSmsRx rx;
    struct dmrSmsRxResult res;

    dmrSmsRx_reset(&rx);
    dmrSms_packetBurst(&pkt, 0, &dt, info);
    info[8] ^= 1; /* inside the destination field */
    memset(&res, 0, sizeof(res));
    check(dmrSmsRx_feed(&rx, dt, info, &res) == 0, "corrupt header dropped", NULL);

    /* blocks that arrive without a header are ignored */
    dmrSmsRx_reset(&rx);
    dmrSms_packetBurst(&pkt, 1, &dt, info);
    memset(&res, 0, sizeof(res));
    check(dmrSmsRx_feed(&rx, dt, info, &res) == 0, "orphan block ignored", NULL);
    return 0;
}

/* ------------------------------------------------------------ long text --- */

static void longText(void)
{
    char text[DMR_SMS_TEXT_MAX + 8];
    static const char * const alphabet =
        "abcdefghijklmnopqrstuvwxyz0123456789 ";

    for (unsigned i = 0; i < DMR_SMS_TEXT_MAX; i++)
        text[i] = alphabet[i % strlen(alphabet)];
    text[DMR_SMS_TEXT_MAX] = '\0';

    struct dmrSmsEncode req;
    struct dmrSmsPacket pkt;
    struct dmrSmsMessage m;

    memset(&req, 0, sizeof(req));
    req.app = DMR_SMS_APP_IP;
    req.src = 1;
    req.dst = 2;
    req.text = text;
    check(dmrSms_encode(&req, &pkt) == 0, "160 characters encode", NULL);
    check(pkt.blockCount == DMR_SMS_BLOCKS_MAX || pkt.blockCount == 30,
          "160 characters take 30 blocks", NULL);
    check(dmrSms_decodePacket(pkt.header, (const uint8_t (*)[12])pkt.blocks,
                              pkt.blockCount, &m) == 0, "160 characters decode",
          NULL);
    check(strcmp(m.text, text) == 0, "160 characters text", NULL);

    /* a text too long for one packet is cut on a character boundary */
    memset(text, 'x', sizeof(text) - 1);
    text[sizeof(text) - 1] = '\0';
    req.text = text;
    check(dmrSms_encode(&req, &pkt) == 0, "oversized text still encodes", NULL);
    check(pkt.truncated, "oversized text is marked truncated", NULL);
    check(dmrSms_decodePacket(pkt.header, (const uint8_t (*)[12])pkt.blocks,
                              pkt.blockCount, &m) == 0, "truncated text decodes",
          NULL);
    check(m.textLen > 0, "truncated text is not empty", NULL);
}

/* ------------------------------------------------------------------ main --- */

int main(int argc, char **argv)
{
    const char *ref = NULL;
    int verbose = 0;

    for (int i = 1; i < argc; i++) {
        if ((strcmp(argv[i], "--ref") == 0) && (i + 1 < argc))
            ref = argv[++i];
        else if (strcmp(argv[i], "--verbose") == 0)
            verbose = 1;
        else {
            printf("usage: %s [--ref tests/unit/assets/dmr_sms_ref.txt]\n",
                   argv[0]);
            return 2;
        }
    }

    if (ref != NULL)
        refCheck(ref);
    packetRoundTrip();
    burstRoundTrip();
    ackTests();
    audioLoop(verbose);
    damageTests();
    longText();

    printf("%u checks, %u failures\n", checks, failures);
    if (failures != 0) {
        printf("RESULT FAIL\n");
        return 1;
    }
    printf("RESULT OK: encoder, decoder, transmit chain and PHY agree\n");
    return 0;
}
