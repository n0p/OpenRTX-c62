/*
 * Host harness for DMR short messages: the firmware encoder, the firmware
 * decoder, the firmware transmit chain and the firmware PHY, in one process.
 *
 *   cc -O2 -std=gnu17 -I openrtx/include tests/platform/c62_sms_host.c \
 *      openrtx/src/protocols/DMR/DmrDefs.c openrtx/src/protocols/DMR/DmrFec.c \
 *      openrtx/src/protocols/DMR/DmrPhy.c openrtx/src/protocols/DMR/DmrTx.c \
 *      openrtx/src/protocols/DMR/DmrTxTables.c \
 *      openrtx/src/protocols/DMR/DmrSms.c openrtx/src/protocols/DMR/DmrSmsApp.c \
 *      -lm -o c62_sms_host
 *
 *   c62_sms_host                                  # self tests
 *   c62_sms_host --ref tests/unit/assets/dmr_sms_ref.txt   # + reference
 *
 * What it checks:
 *
 *  1. Reference: for every message of tests/unit/assets/dmr_sms_ref.txt, which
 *     was generated by the host prototype in work/dmr-sms (the implementation
 *     validated against ETSI TS 102 361-1/-3 and the seven payload flavours
 *     seen on the air), the 196 BPTC bits, the slot type Golay word and the
 *     sync word of every burst are identical.  The 24 CACH bits are not
 *     compared: they belong to the repeater that repeats the call, and the
 *     prototype's generator fills them with a fixed pattern of its own.
 *  2. Round trip at packet level: encode -> decodePacket -> same text, same
 *     addresses, CRC-32 ok, same application detected.
 *  3. Round trip through the reassembler, burst by burst, as OpMode_DMR feeds
 *     it (data header, then rate 1/2 blocks).
 *  4. Delivery response: a C_RHEAD built by dmrSms_buildResponse() is decoded
 *     by the same reassembler, and a TMS acknowledgement record is recognised.
 *  5. Audio loop: message -> dmrTx_dataSlot() -> 48 kHz samples ->
 *     dmrPhy_push() -> decoded bursts -> dmrSmsRx_feed() -> same text.  This
 *     is the whole firmware transmit and receive path with no radio.
 *  6. Damage: one flipped bit in a data block is corrected by BPTC (same
 *     text); a flipped header bit drops the message (no text, no garbage).
 */

