/*
 * Codec2 3200 cost harness: one frame of encode or decode, repeated, on an
 * emulated Cortex-M33 (QEMU mps2-an505) with the instruction counter of
 * scripts/codec_cost.sh.  Same harness builds for the host, so the script can
 * check that the bare-metal build decodes the same samples as the host one
 * before it believes the instruction count.
 *
 *   -DMODE_ENC  encode 160 samples -> 8 bytes  (what M17 transmit runs)
 *   -DMODE_DEC  decode 8 bytes -> 160 samples  (what M17 receive runs)
 *   -DFRAMES=n  calls inside the measured loop (1 and 21 give the slope)
 *
 * The input is 160-sample frames of codec2's own raw/hts1a.raw (8 kHz speech),
 * generated by the script into data_codec2.c: no file I/O in the harness, so
 * nothing but the codec is inside the measurement.
 *
 * Output: "CODEC2 mode=... frames=... hash=..." on the console.  hash is a
 * FNV-1a over every byte the codec produced; the host and the target must
 * agree on it.
 */
#include <stdint.h>

#include "codec2.h"
#include "defines.h"
#include "harness_out.h"

/* codebooknewamp2*.c are generated by codec2's cmake build from the raw
 * codebooks and are not in this tree.  Only the 700C/1600/2400 modes read
 * them, and the 3200 mode never does, but codec2_decode()/codec2_encode()
 * reference those modes' entry points, so the linker needs the symbols.
 * Weak, so a real table from a future codec2 package wins without a change. */
__attribute__((weak)) const struct lsp_codebook newamp2vq_cb[1] = {{0, 0, 0, 0}};
__attribute__((weak)) const struct lsp_codebook newamp2_energy_cb[1] = {{0, 0, 0, 0}};

extern const int16_t speech_c2[];   /* [NFRAMES_C2][160] */
extern const unsigned NFRAMES_C2;

#ifndef FRAMES
#define FRAMES 20
#endif
#ifndef WARMUP
#define WARMUP 4
#endif

#if !defined(MODE_ENC) && !defined(MODE_DEC)
#error "define MODE_ENC or MODE_DEC"
#endif

static volatile uint32_t sink;

static uint32_t fnv1a(uint32_t h, const uint8_t *p, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        h ^= p[i];
        h *= 16777619u;
    }
    return h;
}

int main(void)
{
    struct CODEC2 *c2 = codec2_create(CODEC2_MODE_3200);
    if (c2 == NULL)
        return 1;

    const int nSamples = codec2_samples_per_frame(c2);
    const int nBytes = (codec2_bits_per_frame(c2) + 7) / 8;
    uint8_t bits[16];
    int16_t pcm[160];
    uint32_t hash = 2166136261u;
    int64_t sum = 0;

#ifdef MODE_DEC
    /* Bitstream first: its cost is a constant of the run and cancels out of
     * the FRAMES=1 vs FRAMES=21 difference. */
    uint8_t stream[64][16];
    for (unsigned i = 0; i < 64; i++)
        codec2_encode(c2, stream[i % 64], (int16_t *)&speech_c2[(i % NFRAMES_C2) * nSamples]);
#endif

    for (unsigned i = 0; i < WARMUP; i++) {
#ifdef MODE_ENC
        codec2_encode(c2, bits, (int16_t *)&speech_c2[(i % NFRAMES_C2) * nSamples]);
        hash = fnv1a(hash, bits, nBytes);
#else
        codec2_decode(c2, pcm, stream[i % 64]);
        hash = fnv1a(hash, (const uint8_t *)pcm, nSamples * sizeof(int16_t));
#endif
    }

    for (unsigned i = 0; i < FRAMES; i++) {
#ifdef MODE_ENC
        codec2_encode(c2, bits, (int16_t *)&speech_c2[(i % NFRAMES_C2) * nSamples]);
        if (i + 1 == FRAMES) {
            hash = fnv1a(hash, bits, nBytes);
            for (int k = 0; k < nBytes; k++)
                sum += bits[k];
        }
        sink += bits[0];
#else
        codec2_decode(c2, pcm, stream[i % 64]);
        if (i + 1 == FRAMES) {
            hash = fnv1a(hash, (const uint8_t *)pcm, nSamples * sizeof(int16_t));
            for (int k = 0; k < nSamples; k++)
                sum += pcm[k];
        }
        sink += (uint16_t)pcm[0];
#endif
    }

    char line[96], *p = line;
#ifdef MODE_ENC
    p = hout_lit(p, "CODEC2 mode=enc frames=");
#else
    p = hout_lit(p, "CODEC2 mode=dec frames=");
#endif
    p = hout_dec(p, FRAMES);
    p = hout_lit(p, " samples=");
    p = hout_dec(p, (uint32_t)nSamples);
    p = hout_lit(p, " bytes=");
    p = hout_dec(p, (uint32_t)nBytes);
    p = hout_lit(p, " hash=");
    p = hout_hex32(p, hash);
    p = hout_lit(p, " sum=");
    p = hout_i64(p, sum);
    p = hout_lit(p, "\n");
    *p = '\0';
    hout_str(line);
    codec2_destroy(c2);
    return (int)sink & 0;
}
