/*
 * One control-channel TSDU as bits, for the P25 PHY tests.
 *
 * Real off-air bits: the first TSBK frame the firmware PHY cuts from
 * work/p25-rx/samples/P25_C4FM-CC_BEE0014C_IF.wav (its discriminator dumped at
 * 24 kHz and upsampled to 48 kHz), at symbol 108, NAC 0x140, DUID 0x7, first
 * trellis block with a good CRC-16.  720 bits: the 48 of the sync, the 64-bit
 * NID and three 196-bit blocks with their status symbols, i.e. 360 symbols of
 * the 4800 symbol/s air - the length a control-channel frame really has, as
 * opposed to the 864 of a voice LDU.
 */

#ifndef P25_TEST_TSDU_BITS_H
#define P25_TEST_TSDU_BITS_H

#include <stdint.h>

/** Frame span, sync included. */
#define P25_TEST_TSDU_BITS 720
#define P25_TEST_TSDU_SYMBOLS 360

/** Network access code the NID carries. */
#define P25_TEST_TSDU_NAC 0x140u

/** Data unit ID the NID carries (TSBK, i.e. a TSDU). */
#define P25_TEST_TSDU_DUID 0x7u

static const uint8_t p25_test_tsdu_bytes[P25_TEST_TSDU_BITS / 8] = {
    0x55, 0x75, 0xF5, 0xFF, 0x77, 0xFF, 0x14, 0x07, 0x03, 0xFF, 0x0A, 0x26,
    0xB8, 0x21, 0x0B, 0x89, 0x4C, 0xA6, 0xE0, 0x09, 0x59, 0xF2, 0xC1, 0x6F,
    0x2C, 0x3D, 0xCE, 0xE0, 0xB9, 0xE5, 0x44, 0x2E, 0x76, 0xEC, 0xBC, 0x0A,
    0x17, 0x00, 0x14, 0xD2, 0x62, 0x22, 0x22, 0x22, 0xE2, 0x6F, 0x89, 0xC8,
    0x88, 0x88, 0x87, 0x24, 0x07, 0x8A, 0x22, 0x22, 0x29, 0x0F, 0x04, 0x22,
    0x22, 0x22, 0x2F, 0x3A, 0x00, 0x64, 0xB3, 0xE2, 0x21, 0x4B, 0x61, 0x5E,
    0x22, 0xE8, 0x88, 0x82, 0x24, 0x80, 0x22, 0x28, 0x8A, 0x20, 0x89, 0xA3,
    0x48, 0x8A, 0x22, 0x20, 0xB1, 0x22,
};

#endif /* P25_TEST_TSDU_BITS_H */
