#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

#include "ambe_common.h"
#include "ambe3600x2400_const.h"
#include "ambe3600x2400_internal.h"
#include "mbe_adaptive.h"
#include "mbe_tone.h"
#include "mbelib-neo/mbelib.h"

/* The 321-sample synthesis window lives in a private header of the reference
 * (static const, so including it here cannot collide with anything). */
#include "mbelib_const.h"

static void print_float_array(const char *name, const float *v, int n,
                              const char *comment)
{
    printf("\n/* %s */\nstatic const float %s[%d] = {", comment, name, n);
    for (int i = 0; i < n; i++) {
        if ((i % 6) == 0)
            printf("\n    ");
        printf("%a%s", (double)v[i], i + 1 < n ? ", " : ",\n");
    }
    printf("};\n");
}

int main(void)
{
    printf("/* Generated by lib/dstar_vocoder/tools/gen_tables.c from mbelib-neo\n"
           " * v2.6.2 (GPL-2.0-or-later).  Do not edit: regenerate instead.\n"
           " *\n"
           " * SPDX-FileCopyrightText: 2026 OpenRTX Contributors\n"
           " *\n"
           " * SPDX-License-Identifier: GPL-2.0-or-later\n"
           " */\n");
    printf("\n#ifndef DSTAR_TABLES_H\n#define DSTAR_TABLES_H\n\n#include <stdint.h>\n");

    /* ---- AMBE 2400 quantiser codebooks ------------------------------- */
    {
        float dg[64];
        for (int i = 0; i < 64; i++)
            dg[i] = AmbePlusDg[i];
        print_float_array("dstar_dg", dg, 64,
                          "gain codebook: gamma = 2*Dg[b2] - 0.09");

        float prba24[512 * 3];
        for (int i = 0; i < 512; i++)
            for (int j = 0; j < 3; j++)
                prba24[i * 3 + j] = AmbePlusPRBA24[i][j];
        print_float_array("dstar_prba24", prba24, 512 * 3,
                          "PRBA block 2-4 (b3), Gm[2..4] per code");

        float prba58[128 * 4];
        for (int i = 0; i < 128; i++)
            for (int j = 0; j < 4; j++)
                prba58[i * 4 + j] = AmbePlusPRBA58[i][j];
        print_float_array("dstar_prba58", prba58, 128 * 4,
                          "PRBA block 5-8 (b4), Gm[5..8] per code");

        static const float *hoc[4] = {NULL, NULL, NULL, NULL};
        (void)hoc;
        float b5[16 * 4], b6[16 * 4], b7[16 * 4], b8[16 * 4];
        for (int i = 0; i < 16; i++) {
            for (int j = 0; j < 4; j++) {
                b5[i * 4 + j] = AmbePlusHOCb5[i][j];
                b6[i * 4 + j] = AmbePlusHOCb6[i][j];
                b7[i * 4 + j] = AmbePlusHOCb7[i][j];
                b8[i * 4 + j] = AmbePlusHOCb8[i][j];
            }
        }
        print_float_array("dstar_hoc_b5", b5, 64, "HOC codebook of block 1 (b5)");
        print_float_array("dstar_hoc_b6", b6, 64, "HOC codebook of block 2 (b6)");
        print_float_array("dstar_hoc_b7", b7, 64, "HOC codebook of block 3 (b7)");
        print_float_array("dstar_hoc_b8", b8, 64, "HOC codebook of block 4 (b8)");
    }

    /* ---- small integer tables ---------------------------------------- */
    printf("\n/* V/UV vector of the 4-bit b1 code, indexed by jl = 16*l*f0 */\n"
           "static const uint8_t dstar_vuv[16][8] = {");
    for (int i = 0; i < 16; i++) {
        printf("\n    {");
        for (int j = 0; j < 8; j++)
            printf("%d%s", AmbePlusVuv[i][j], j < 7 ? ", " : "");
        printf("}%s", i < 15 ? "," : ",\n");
    }
    printf("};\n");

    printf("\n/* HOC block length per harmonic count: Ji[1..4] */\n"
           "static const uint8_t dstar_lmprbl[57][4] = {");
    for (int i = 0; i < 57; i++) {
        printf("\n    {");
        for (int j = 0; j < 4; j++)
            printf("%d%s", AmbePlusLmprbl[i][j], j < 3 ? ", " : "");
        printf("}%s", i < 56 ? "," : ",\n");
    }
    printf("};\n");

    /* ---- pitch and harmonic count ------------------------------------ */
    float w0[128], f0tab[128];
    int L[128];
    int maxJi = 1;
    /* w0 and L are taken from the reference itself, by decoding a frame whose
     * pitch code is b0: recomputing them here would repeat the reference's
     * arithmetic and be off by a few ulp where exp2f() rounds differently
     * between the library build and this one (16 of the 128 codes). */
    static const int b0bits[7] = {0, 1, 2, 3, 4, 5, 48};
    for (int b0 = 0; b0 < 128; b0++) {
        static mbe_parms cur, prev, enh;
        char d[49];
        memset(d, 0, sizeof(d));
        for (int i = 0; i < 7; i++)
            d[b0bits[i]] = (char)((b0 >> (6 - i)) & 1);
        mbe_initMbeParms(&cur, &prev, &enh);
        if (mbe_decodeAmbe2400Parms(d, &cur, &prev) != 0 || cur.L < 1) {
            /* a tone or silence code: no voice model, keep the pitch law */
            f0tab[b0] = mbe_ambe2400_f0(b0);
            w0[b0] = (float)((double)(f0tab[b0] * 2.0f) * M_PI);
            L[b0] = mbe_ambe2400_harmonic_count(f0tab[b0]);
            continue;
        }
        f0tab[b0] = mbe_ambe2400_f0(b0);
        w0[b0] = cur.w0;
        L[b0] = cur.L;
    }
    for (int i = 0; i < 57; i++)
        for (int j = 0; j < 4; j++)
            if (AmbePlusLmprbl[i][j] > maxJi)
                maxJi = AmbePlusLmprbl[i][j];

    print_float_array("dstar_w0", w0, 128,
                      "fundamental, rad/sample, per pitch code b0");
    print_float_array("dstar_f0", f0tab, 128,
                      "fundamental, cycles/sample, per pitch code b0");
    printf("\n/* harmonic count per pitch code b0 */\n"
           "static const uint8_t dstar_l[128] = {");
    for (int b0 = 0; b0 < 128; b0++)
        printf("%s%d,", (b0 % 20) == 0 ? "\n    " : " ", L[b0]);
    printf("\n};\n");
    printf("\n/* harmonic count the silence and initial models use */\n"
           "#define DSTAR_SILENCE_W0 ((float)%a)\n#define DSTAR_SILENCE_L %d\n",
           (double)MBE_AMBE_SILENCE_W0, MBE_AMBE_SILENCE_L);
    printf("#define DSTAR_MAX_JI %d\n", maxJi);

    /* ---- DCT cosines (as the reference computes them) ---------------- */
    {
        const struct ambe_dct_cache *c = mbe_ambe2400_get_dct_cache();
        float ri[9 * 9];
        for (int m = 0; m < 9; m++)
            for (int i = 0; i < 9; i++)
                ri[m * 9 + i] = (m == 0 || i == 0) ? 0.0f : c->ri_cos[m][i];
        print_float_array("dstar_ri_cos", ri, 81,
                          "cos(pi*(m-1)*(i-0.5)/8), [m][i]");

        /* ragged per-block inverse DCT, offsets in floats */
        int off[19];
        int total = 0;
        for (int ji = 0; ji <= 18; ji++) {
            off[ji] = total;
            if (ji >= 1 && ji <= 17)
                total += ji * ji;
        }
        float *idct = calloc((size_t)total, sizeof(float));
        for (int ji = 1; ji <= 17; ji++) {
            for (int j = 1; j <= ji; j++)
                for (int k = 1; k <= ji; k++)
                    idct[off[ji] + (j - 1) * ji + (k - 1)] = c->idct_cos[ji][j][k];
        }
        print_float_array("dstar_idct_cos", idct, total,
                          "cos(pi*(k-1)*(j-0.5)/ji), ragged by block length");
        printf("\n/* offset of each block length in dstar_idct_cos */\n"
               "static const uint16_t dstar_idct_off[19] = {");
        for (int ji = 0; ji <= 18; ji++)
            printf("%s%u,", (ji % 10) == 0 ? "\n    " : " ", (unsigned)off[ji]);
        printf("\n};\n");
        free(idct);
    }

    /* ---- tone amplitudes: 8-bit D-STAR volume -> float gain ---------- */
    {
        float amp[256];
        for (int v = 0; v < 256; v++) {
            /* mbe_synthesizeTonefdstar(): gain = mbe_toneAmplitude(level_db) */
            const double level_db = mbe_tone_dstar_level_db(v);
            amp[v] = (float)(sqrt(2.0) * 32768.0 * pow(10.0, level_db / 20.0) / 7.0);
        }
        print_float_array("dstar_tone_amp", amp, 256,
                          "tone gain per 8-bit D-STAR volume, float scale");
    }

    /* ---- log2 of the integer harmonic counts ------------------------- */
    {
        float lg[57];
        for (int i = 0; i < 57; i++)
            lg[i] = (i >= 1) ? log2f((float)i) : 0.0f;
        print_float_array("dstar_log2_l", lg, 57, "log2f(L) for L = 1..56");
    }

    /* ---- the 321-sample synthesis window ----------------------------- */
    print_float_array("dstar_ws", Ws, 321,
                      "voiced synthesis window Ws[0..320]");

    printf("\n#endif /* DSTAR_TABLES_H */\n");
    return 0;
}
