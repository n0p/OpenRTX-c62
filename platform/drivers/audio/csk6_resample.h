#ifndef CSK6_RESAMPLE_H
#define CSK6_RESAMPLE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * 48 kHz <-> 8 kHz polyphase resampler for the CSK6 audio transport.
 *
 * Every voice mode of the C62 works at 8 kHz while the DSP transports 48 kHz
 * stereo, and the driver used to bridge the two by keeping one sample in six
 * and repeating each sample six times.  That is a resampler with no filter: in
 * capture everything between 4 and 24 kHz folds into the voice band at full
 * level (a 6,5 kHz whistle arrives at the vocoder as 1,5 kHz), and in playback
 * the zero-order hold leaves the first image at 8 kHz only 13,5 dB down
 * (reports/codecs.md section 2.8).
 *
 * This is the replacement: a 48-tap low-pass, split into six phases of eight
 * taps, Q15, 32/64-bit accumulator.  script/csk6_resample_design.py designs it
 * and checks it; the numbers below are that script's output for this table.
 *
 *   passband   100 Hz -0,000 dB, 1 kHz -0,010, 2 kHz -0,041, 2,5 kHz -0,40,
 *              3 kHz -1,5, 3,4 kHz -3,2 (a 4 kHz telephony band edge)
 *   stopband   4 kHz -7,9 dB, 4,5 kHz -14,4, 5 kHz -24,4, 5,5 kHz -41,7,
 *              6 kHz -62,3, 6,5 kHz -70,8, 7 kHz -77,4, 9 kHz -79,8
 *   measured   6,5 kHz in -> 1,5 kHz alias at -82 dB (was 0 dB)
 *              1 kHz in -> images at 7 kHz -77 dB, 9 kHz -81 dB (was -13,5)
 *
 * The transition band is the price of 48 taps, which is the cost envelope the
 * report measured (63 k instructions per 10 ms block for both directions, 2,5 %
 * of the M33).  At 48 kHz a 1 ms window cannot be steeper: 60 dB of stopband
 * from 4 kHz would need about 260 taps with this window, and every extra phase
 * tap is paid 6 times in the interpolator.  Between 4 and 5,5 kHz the old
 * unfiltered path gave 0 dB and this gives 8 to 42 dB.
 *
 * Both directions keep their history across calls, so a 10 ms DSP frame is not
 * a filter boundary: the phase and the last eight samples of every branch
 * persist.  The state is small (about 200 B per direction) and is meant to go
 * where the driver already keeps its stream state (PSRAM on the C62), so the
 * DTCM footprint does not change.
 *
 * The kernels are static inline in this header on purpose: csk6_codec.c and
 * tests/qemu/resample_cost.c include the same text, so the instruction counts
 * the cost script reports are those of the shipping code, not of a copy of it.
 */

#define CSK6_RESAMPLE_PHASES 6 ///< 48 kHz / 8 kHz
#define CSK6_RESAMPLE_TAPS   8 ///< Taps per phase: 48 in all

/*
 * Decimator, 48 kHz -> 8 kHz.  csk6_dec_coef[b][i] multiplies win[i] of branch
 * b, where win[0] is the sample eight branch entries back and win[7] the newest
 * one.  Branch b holds the input samples whose index is congruent to b modulo
 * six; the output is taken as the sixth sample of a group arrives, so tap j of
 * the prototype lives in branch (5 - j) % 6 at j / 6 entries of distance.
 * Generated by scripts/csk6_resample_design.py --tables.
 */
static const int16_t csk6_dec_coef[CSK6_RESAMPLE_PHASES][CSK6_RESAMPLE_TAPS] = {
    {    -5,    66,  -241,   643,  5126,  -119,   -24,    16 },
    {   -13,   126,  -488,  1644,  4665,  -580,   121,   -14 },
    {   -21,   175,  -689,  2762,  3828,  -750,   182,   -24 },
    {   -24,   182,  -750,  3828,  2762,  -689,   175,   -21 },
    {   -14,   121,  -580,  4665,  1644,  -488,   126,   -13 },
    {    16,   -24,  -119,  5126,   643,  -241,    66,    -5 },
};

/*
 * Interpolator, 8 kHz -> 48 kHz.  csk6_int_coef[p][i] multiplies win[i] of the
 * input history, win[7] being the newest input sample, and gives output p of
 * the six the sample produces.  The taps carry the factor six that zero
 * stuffing takes out of the level, so a full-scale input stays full scale.
 */
static const int16_t csk6_int_coef[CSK6_RESAMPLE_PHASES][CSK6_RESAMPLE_TAPS] = {
    {    97,  -143,  -711, 30754,  3857, -1448,   398,   -30 },
    {   -84,   726, -3483, 27990,  9865, -2929,   757,   -77 },
    {  -146,  1093, -4501, 22966, 16570, -4135,  1047,  -128 },
    {  -128,  1047, -4135, 16570, 22966, -4501,  1093,  -146 },
    {   -77,   757, -2929,  9865, 27990, -3483,   726,   -84 },
    {   -30,   398, -1448,  3857, 30754,  -711,  -143,    97 },
};

/** Decimator state: one eight-deep history per phase, plus the group phase. */
struct csk6Decimator
{
    int16_t hist[CSK6_RESAMPLE_PHASES][2 * CSK6_RESAMPLE_TAPS]; ///< Doubled
    uint8_t head;  ///< Next slot to write, 0..7
    uint8_t phase; ///< Phase that receives the next sample, 0..5
};

/** Interpolator state: the last eight input samples, doubled to read linearly. */
struct csk6Interpolator
{
    int16_t hist[2 * CSK6_RESAMPLE_TAPS]; ///< Doubled history
    int16_t out[CSK6_RESAMPLE_PHASES];    ///< The six outputs of the last push
    uint8_t head;                         ///< Next slot to write, 0..7
};

/**
 * Sum of eight tap products, 32-bit accumulator.
 *
 * The eight terms are written out on purpose: the firmware builds its sources
 * at -Os, where the loop costs about 30 % more than the unrolled sum (measured,
 * scripts/codec_cost.sh: 55 626 against 70 283 instructions per 10 ms block
 * for both directions).  Eight is CSK6_RESAMPLE_TAPS, the taps per phase.
 */
static inline __attribute__((always_inline)) int32_t
csk6_resample_dot8(const int16_t *c, const int16_t *w)
{
    return (int32_t)c[0] * w[0] + (int32_t)c[1] * w[1]
         + (int32_t)c[2] * w[2] + (int32_t)c[3] * w[3]
         + (int32_t)c[4] * w[4] + (int32_t)c[5] * w[5]
         + (int32_t)c[6] * w[6] + (int32_t)c[7] * w[7];
}

/**
 * Sum of eight tap products, 64-bit accumulator: the interpolator's taps add up
 * to six times Q15, so sum(|c|) * 32 768 does not fit in 32 bits.  On the
 * Cortex-M33 each product is one SMLAL into the accumulator pair.
 */
static inline __attribute__((always_inline)) int64_t
csk6_resample_dot8_64(const int16_t *c, const int16_t *w)
{
    return (int64_t)c[0] * w[0] + (int64_t)c[1] * w[1]
         + (int64_t)c[2] * w[2] + (int64_t)c[3] * w[3]
         + (int64_t)c[4] * w[4] + (int64_t)c[5] * w[5]
         + (int64_t)c[6] * w[6] + (int64_t)c[7] * w[7];
}

/**
 * Clamp a filtered sample to the 16-bit range.
 */
static inline int16_t csk6_resample_sat(int32_t v)
{
    if (v > 32767)
        return 32767;
    if (v < -32768)
        return -32768;
    return (int16_t)v;
}

/**
 * Forget the decimator's history.  Call it when a stream starts, so that the
 * samples of a previous stream do not ring into the new one.
 */
static inline void csk6Decim_reset(struct csk6Decimator *s)
{
    for (unsigned int b = 0; b < CSK6_RESAMPLE_PHASES; b++) {
        for (unsigned int i = 0; i < 2 * CSK6_RESAMPLE_TAPS; i++)
            s->hist[b][i] = 0;
    }
    s->head = 0;
    s->phase = 0;
}

/**
 * Forget the interpolator's history.
 */
static inline void csk6Interp_reset(struct csk6Interpolator *s)
{
    for (unsigned int i = 0; i < 2 * CSK6_RESAMPLE_TAPS; i++)
        s->hist[i] = 0;
    for (unsigned int p = 0; p < CSK6_RESAMPLE_PHASES; p++)
        s->out[p] = 0;
    s->head = 0;
}

/**
 * Feed one 48 kHz sample to the decimator.
 *
 * @param s: decimator state.
 * @param x: input sample.
 * @param y: when the function returns true, the 8 kHz output sample.
 * @return true every six inputs, false otherwise.
 */
static inline __attribute__((always_inline)) bool
csk6Decim_push(struct csk6Decimator *s, int16_t x, int16_t *y)
{
    /*
     * The history is stored twice so that the eight taps of every branch are
     * always a linear run of memory, whatever `head` is: the window is
     * hist[b][head + 1 .. head + 8], which ends on the sample just written.
     * Sum of |coefficients| is 42 890 (Q15), so the 32-bit accumulator cannot
     * overflow: 32 768 * 42 890 < 2^31.
     */
    s->hist[s->phase][s->head] = x;
    s->hist[s->phase][s->head + CSK6_RESAMPLE_TAPS] = x;

    if (s->phase != CSK6_RESAMPLE_PHASES - 1) {
        s->phase++;
        return false;
    }
    s->phase = 0;

    int32_t acc = 0;
    for (unsigned int b = 0; b < CSK6_RESAMPLE_PHASES; b++)
        acc += csk6_resample_dot8(csk6_dec_coef[b], &s->hist[b][s->head + 1]);

    s->head = (s->head + 1) & (CSK6_RESAMPLE_TAPS - 1);
    *y = csk6_resample_sat(acc >> 15);
    return true;
}

/**
 * Feed one 8 kHz sample to the interpolator.  The six 48 kHz outputs it
 * produces are then read with csk6Interp_out().
 *
 * @param s: interpolator state.
 * @param x: input sample.
 */
static inline __attribute__((always_inline)) void
csk6Interp_push(struct csk6Interpolator *s, int16_t x)
{
    /*
     * Same doubled history as the decimator, over the input samples this time.
     * The accumulator is 64 bits: the taps sum to 196 610 (six times Q15), so
     * sum(|c|) * 32 768 does not fit in 32 bits for an input near full scale.
     * On the Cortex-M33 that is one SMLAL per tap, the same cost as MLA.
     */
    s->hist[s->head] = x;
    s->hist[s->head + CSK6_RESAMPLE_TAPS] = x;

    for (unsigned int p = 0; p < CSK6_RESAMPLE_PHASES; p++) {
        int64_t acc = csk6_resample_dot8_64(csk6_int_coef[p],
                                            &s->hist[s->head + 1]);
        s->out[p] = csk6_resample_sat((int32_t)(acc >> 15));
    }

    s->head = (s->head + 1) & (CSK6_RESAMPLE_TAPS - 1);
}

/**
 * One of the six 48 kHz samples the last csk6Interp_push() produced.
 *
 * @param s: interpolator state.
 * @param p: 0..5, the phase.
 * @return the output sample.
 */
static inline int16_t csk6Interp_out(const struct csk6Interpolator *s,
                                     unsigned int p)
{
    /* No mask by PHASES - 1 here: six is not a power of two and 5 & 5 is 1. */
    return s->out[p < CSK6_RESAMPLE_PHASES ? p : 0];
}

#endif /* CSK6_RESAMPLE_H */
