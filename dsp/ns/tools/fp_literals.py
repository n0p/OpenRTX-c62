#!/usr/bin/env python3
"""Rewrite floating-point literals with an `f` suffix, for the DSP build.

usage: fp_literals.py <src.c> <dst.c>

Why this exists: the firmware builds lib/rnnoise with -fsingle-precision-constant
(lib/rnnoise/CMakeLists.txt), so on the Cortex-M33 every `1.3` in the denoiser is
a *float* constant and the arithmetic around it stays in single precision.  The
Xtensa clang 10 in the RI-2021.7 bundle accepts the flag and ignores it, which
would silently turn those expressions into double ones: 101 calls to the
soft-double helpers in __muldf3 & co per frame, and a different last bit in
every place a literal appears.

Rather than lean on a flag that one of the two compilers does not implement,
the DSP build compiles a copy of the sources where the literals are already
float.  Comments, string literals and character constants are left alone, and a
literal that already has a suffix is kept as it is.
"""
import re
import sys

# a floating literal: decimal with a '.' or an exponent, or a hex float
FLOAT = re.compile(r"""
    (?P<hex>0[xX][0-9a-fA-F]*\.[0-9a-fA-F]*(?:[pP][+-]?\d+)?)
  | (?P<dec>(?:\d+\.\d*|\.\d+|\d+(?=[eE]))(?:[eE][+-]?\d+)?)
""", re.X)


def convert(text):
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        # comments
        if text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(text[i:j])
            i = j
            continue
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(text[i:j])
            i = j
            continue
        # string and char literals
        if c in "\"'":
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == c:
                    j += 1
                    break
                j += 1
            out.append(text[i:j])
            i = j
            continue
        m = FLOAT.match(text, i)
        if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_.")):
            lit = m.group(0)
            j = m.end()
            suffix = text[j] if j < n else ""
            if suffix in "fFlL":
                out.append(lit + suffix)   # already typed, leave it
                i = j + 1
                continue
            out.append(lit + "f")
            i = j
            continue
        out.append(c)
        i += 1
    return "".join(out)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    with open(src) as f:
        text = f.read()
    changed = convert(text)
    with open(dst, "w") as f:
        f.write("/* Generated by dsp/ns/tools/fp_literals.py from %s. Do not edit. */\n" % src)
        f.write(changed)
    print(f"{src} -> {dst}")


if __name__ == "__main__":
    main()
