#!/usr/bin/env python3
"""Turn an M33 table dump (bench/tables_main.c) into dsp/ns/ns_tables.h.

usage: gen_tables.py <tables_m33.txt> <out.h>

The values are emitted as C99 hex float literals, which are exact: the header
carries the reference build's bits, not a decimal re-parse of them.  This is
what lib/rnnoise's RNNOISE_FIXED_TABLES mode reads, so the DSP port uses the
M33's tables instead of asking its own libm for them again (the two disagree in
the last bit on a third of the entries).
"""
import struct
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    hw, dct, tw, brv, fac = [], [], [], [], []
    nfft = shift = None
    scale = None
    with open(src) as f:
        for line in f:
            t = line.split()
            if len(t) != 2:
                continue
            k, v = t
            if k == "nfft":
                continue
            if k == "brv":
                brv.append(v)
            elif k == "fac":
                fac.append(v)
            elif k == "scale":
                scale = v
            elif k == "hw":
                hw.append(v)
            elif k == "dct":
                dct.append(v)
            elif k in ("twr", "twi"):
                tw.append(v)
    for line in open(src):
        if line.startswith("nfft"):
            parts = line.split()          # "nfft 960 shift -1"
            nfft, shift = parts[1], parts[3]
    assert nfft == "960" and shift == "-1", (nfft, shift)
    assert scale, "no scale in the dump"
    assert len(brv) == 960, len(brv)
    assert len(fac) == 16, len(fac)
    # kiss_fft fills only the factors it uses; the rest of the array is whatever
    # malloc returned.  Zero the tail so the header is reproducible, and keep the
    # used ones verbatim.
    last = max(i for i, v in enumerate(fac) if int(v) != 0)
    fac = fac[:last + 1] + ["0"] * (16 - last - 1)
    assert len(hw) == 480, len(hw)
    assert len(dct) == 22 * 22, len(dct)
    assert len(tw) == 2 * 960, len(tw)

    def flt(hexbits):
        return struct.unpack("<f", bytes.fromhex(hexbits)[::-1])[0].hex() + "f"

    with open(dst, "w") as o:
        o.write("/*\n"
                " * Generated by dsp/ns/tools/gen_tables.py from the M33 build of\n"
                " * lib/rnnoise (build/tables_m33.txt).  Do not edit.\n"
                " *\n"
                " * Why: these tables are double-precision sin()/cos() results rounded to\n"
                " * float.  newlib on the Cortex-M33 and the Xtensa libm disagree in the last\n"
                " * bit on a third of the entries, which is enough to change every output\n"
                " * sample of the denoiser.  A DSP port that has to match the M33 bit for bit\n"
                " * uses the M33's values.\n"
                " */\n\n"
                "#ifndef NS_TABLES_H\n#define NS_TABLES_H\n\n")
        def w(name, typ, vals, per=4):
            o.write(f"static const {typ} {name}[{len(vals)}] = {{\n")
            for i in range(0, len(vals), per):
                o.write("    " + ", ".join(vals[i:i + per]) + ",\n")
            o.write("};\n\n")
        w("ns_half_window", "float", [flt(v) for v in hw])
        w("ns_dct_table", "float", [flt(v) for v in dct])
        pairs = [f"{{{flt(tw[2*i])}, {flt(tw[2*i+1])}}}" for i in range(960)]
        w("ns_fft_twiddles", "kiss_twiddle_cpx", pairs, per=2)
        w("ns_fft_bitrev", "opus_int16", brv)
        w("ns_fft_factors", "opus_int16", fac)
        scale_line = "    .scale = %s,\n" % flt(scale)
        o.write(
            "/* The whole FFT state, so that check_init() needs neither malloc nor\n"
            " * sin()/cos(): the twiddles are the reference build's, the factors and the\n"
            " * bit-reversal table are integers computed by kiss_fft's own kf_factor() and\n"
            " * are identical on every target. */\n"
            "static const kiss_fft_state ns_fft_state = {\n"
            "    .nfft = 960,\n"
            + scale_line +
            "    .shift = -1,\n"
            "    .factors = { %s, %s, %s, %s,\n" % tuple(fac[0:4])
            + "                 %s, %s, %s, %s,\n" % tuple(fac[4:8])
            + "                 %s, %s, %s, %s,\n" % tuple(fac[8:12])
            + "                 %s, %s, %s, %s },\n" % tuple(fac[12:16])
            + "    .bitrev = ns_fft_bitrev,\n"
            + "    .twiddles = ns_fft_twiddles,\n"
            "    .arch_fft = 0,\n"
            "};\n\n")
        o.write("#endif /* NS_TABLES_H */\n")
    print(f"{dst}: {len(hw)} half-window, {len(dct)} dct, {len(tw)//2} twiddles")


if __name__ == "__main__":
    main()
